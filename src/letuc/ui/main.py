    def _on_reset_settings(self):
        """Throw away the user's config and restore the shipped defaults.

        This is the nuclear option: it wipes every preset, every port, every
        checkbox and every rule the user has typed. It is only useful when
        something is so broken that editing it by hand is worse than
        starting over, so it asks for confirmation first and refuses to run
        while the proxy is up — tearing the service down mid-flight is the
        last thing anyone wants.
        """
        if self.app.client is not None:
            ret = QMessageBox.warning(
                self, "重置设置",
                "代理正在运行。重置会先停止服务再清空所有配置，\n"
                "确定要继续吗？",
                QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                QMessageBox.StandardButton.No)
            if ret != QMessageBox.StandardButton.Yes:
                return
            self._on_stop()

        if os.path.exists(self.app.config.path):
            try:
                os.remove(self.app.config.path)
            except OSError as e:
                logger.warning("failed to remove config: %s", e)
                QMessageBox.warning(self, "重置设置",
                                    "无法删除配置文件：%s" % e)
                return

        # Rebuild from defaults, then refresh every widget that mirrors the
        # config so the UI stops disagreeing with the file.
        self.app.config = Config.load_from_file(self.app.config.path)
        self.app.user_rules = self.app.config.get("rules", default=[]) or []
        self.app.community_rules = _rulesets.build_rules()
        self.app.rebuild_engine()
        self._sync_from_preset()
        self.preset_combo.clear()
        self.preset_combo.addItems(
            [p.get("name", "") for p in
             self.app.config.get("server", "presets", default=[])])
        active = self.app.config.get("server", "active")
        if active in [p.get("name", "") for p in
                      self.app.config.get("server", "presets", default=[])]:
            self.preset_combo.setCurrentText(active)
        self.tun_check.setChecked(
            self.app.config.get("tun", "enabled", default=False))
        self.leak_check.setChecked(
            self.app.config.get("dns", "leak_detection", default=True))
        self.sysproxy_check.setChecked(True)
        self.autostart_check.blockSignals(True)
        self.autostart_check.setChecked(_startup.is_enabled())
        self.autostart_check.blockSignals(False)
        self._refresh_rule_list()
        self.set_status("stopped")
        self.log.appendPlainText("已重置为默认设置")

    def _on_start(self):
        self._persist_config()
        self.start_btn.setDisabled(True)
        self.stop_btn.setDisabled(False)
        task = self.app.loop.create_task(self.app.start_services())
        task.add_done_callback(self._start_finished)

    def _start_finished(self, task):
        """Surface a startup failure instead of leaving a dead client."""
        if task.cancelled():
            return
        exc = task.exception()
        if exc is None:
            return
        logger.error("start failed: %s", exc)
        self.log.appendPlainText("启动失败：%s" % exc)
        self.set_status("start failed")
        self.start_btn.setDisabled(False)
        self.stop_btn.setDisabled(True)

    def _on_stop(self):
        self.stop_btn.setDisabled(True)
        self.start_btn.setDisabled(False)
        task = self.app.loop.create_task(self.app.stop_services())
        task.add_done_callback(self._stop_finished)

    def _stop_finished(self, task):
        if task.cancelled():
            return
        exc = task.exception()
        if exc is not None:
            logger.error("stop failed: %s", exc)
            self.log.appendPlainText("停止时出错：%s" % exc)

    def _persist_config(self):
        cfg = self.app.config
        presets = cfg.get("server", "presets", default=[])
        idx = self.preset_combo.currentIndex()
        if 0 <= idx < len(presets):
            presets[idx]["host"] = self.host_edit.text()
            presets[idx]["port"] = _int_or(self.port_edit.text(), 33009)
            presets[idx]["username"] = self.user_edit.text()
            presets[idx]["password"] = self.pass_edit.text()
            cfg.set(presets, "server", "presets")
            cfg.set(presets[idx].get("name"), "server", "active")
        cfg.set(self.listen_edit.text(), "proxy", "listen")
        cfg.set(_int_or(self.mixed_edit.text(), 20808), "proxy", "mixed")
        cfg.set(_int_or(self.socks_edit.text(), 3080), "proxy", "socks")
        cfg.set(_int_or(self.pac_edit.text(), 20811), "proxy", "pac")
        cfg.set(_int_or(self.xray_edit.text(), 20812), "proxy", "xray_api")
        cfg.set(_int_or(self.mihomo_edit.text(), 20813), "proxy", "mihomo_api")
        cfg.set(_int_or(self.mtu_edit.text(), 1400), "tun", "mtu")
        cfg.set(self.tun_check.isChecked(), "tun", "enabled")
        cfg.set(self.leak_check.isChecked(), "dns", "leak_detection")
        cfg.set(self.sysproxy_check.isChecked(), "anti_detection",
                "set_system_proxy_on_start")
        cfg.save()

    def _on_tun_toggled(self, checked):
        """Install the WinTun driver when the user turns TUN on.

        The bundled wintun.dll is only the user-mode half of the stack;
        the kernel driver is a separate install. Without it every TUN
        attempt fails with WintunCreateAdapter, so ask once here instead
        of letting the user discover it at startup.
        """
        if not checked:
            return
        if _wintun.is_driver_installed():
            return
        if _wintun.ensure_driver(parent=self, prompt=True):
            self.log.appendPlainText("WinTun 驱动安装成功，TUN 可用")
        else:
            self.tun_check.blockSignals(True)
            self.tun_check.setChecked(False)
            self.tun_check.blockSignals(False)
            self.log.appendPlainText(
                "WinTun 驱动未安装，TUN 已禁用（软件代理仍可用）")

    def _on_autostart_toggled(self, checked):
        """Flip the HKCU Run entry when the checkbox is toggled.

        Only meaningful for a frozen executable: running from source
        there is nothing to persist, so tell the user rather than
        silently doing nothing.
        """
        try:
            if checked:
                _startup.enable()
            else:
                _startup.disable()
        except Exception as e:
            logger.warning("auto-start toggle failed: %s", e)
            self.autostart_check.blockSignals(True)
            self.autostart_check.setChecked(not checked)
            self.autostart_check.blockSignals(False)
            QMessageBox.warning(self, "开机自启动", "设置失败：%s" % e)

