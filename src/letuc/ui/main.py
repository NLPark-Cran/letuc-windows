    def _on_add_preset(self):
        name, ok = QInputDialog.getText(self, "新增预设", "预设名称:")
        if not ok or not name.strip():
            return
        name = name.strip()
        presets = self.app.config.get("server", "presets", default=[])
        if any(p.get("name") == name for p in presets):
            QMessageBox.warning(self, "重名", "已存在同名预设。")
