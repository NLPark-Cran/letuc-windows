class TrayIcon:
    def __init__(self, app: LetucApp):
        self.app = app
        self.tray = QSystemTrayIcon(_app_icon())
        self.menu = QMenu()
        self.show_action = self.menu.addAction("显示")
        self.start_action = self.menu.addAction("启动")
        self.stop_action = self.menu.addAction("停止")
        self.quit_action = self.menu.addAction("停止代理并完全退出")
        self.tray.setContextMenu(self.menu)
        self.tray.activated.connect(self._on_activated)
        self.show_action.triggered.connect(self.app.window.show)
        self.start_action.triggered.connect(self._start)
        self.stop_action.triggered.connect(self._stop)
        # _quit is a coroutine; connecting it directly would create the
        # coroutine and never run it, which is how "停止代理并完全退出"
        # used to silently do nothing.
        self.quit_action.triggered.connect(
            lambda: self.app.loop.create_task(self.app._quit()))
        if self.tray.isSystemTrayAvailable():
            self.tray.show()

    def _start(self):
        self.app.window._on_start()

    def _stop(self):
        self.app.window._on_stop()

    def _on_activated(self, reason):
        if reason == QSystemTrayIcon.TriggerReason.DoubleClick:
            self.app.window.show()


