    def closeEvent(self, event):
        """Minimize to tray instead of closing.

        Closing the window should not tear the proxy down — that is what
        the tray's quit entry is for. Hiding here keeps the service alive
        and lets the user come back by double-clicking the icon.
        """
        event.ignore()
        self.hide()

