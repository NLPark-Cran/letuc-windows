def _app_icon():
    """Load the application icon, falling back to a blank icon if missing.

    The icon is generated by make_icon.py from the user's avatar and lives
    in assets/letuc.ico next to the source tree. When the app is frozen the
    assets are extracted into PyInstaller's temporary directory, NOT next
    to the exe — looking only at the exe's own directory is why the tray
    and window showed a blank square even though the icon was embedded.
    """
    icon = QIcon()
    bases = []
    if getattr(sys, "frozen", False):
        # PyInstaller extracts bundled data to sys._MEIPASS before the
        # application starts. The spec bundles assets/letuc.ico with dest
        # "assets", so the real location is _MEIPASS\assets\letuc.ico —
        # searching _MEIPASS root or the exe's own directory misses it and
        # the tray shows an empty placeholder.
        meipass = getattr(sys, "_MEIPASS", None)
        if meipass:
            bases.append(meipass)
            bases.append(os.path.join(meipass, "assets"))
        exe_dir = os.path.dirname(sys.executable)
        bases.append(exe_dir)
        bases.append(os.path.join(exe_dir, "assets"))
    here = os.path.dirname(os.path.abspath(__file__))
    bases.append(here)
    bases.append(os.path.join(here, "assets"))
    for base in bases:
        for name in ("letuc.ico", "letuc.png"):
            p = os.path.join(base, name)
            if os.path.exists(p):
                icon.addFile(p)
                if not icon.isNull():
                    return icon
    return icon


# ---------------------------------------------------------------------------
# Simple rule syntax
# ---------------------------------------------------------------------------
#
# The rules tab is a plain text box. Each line is one rule, written the way
# you would say it out loud:
#
#     google.com 走代理
#     *.cn 需要直连
#     192.168.0.0/16 需要直连
#     baidu.com 要直连
#     8.8.8.8 需要屏蔽
#
# The tail keyword decides the outbound:
#   需要直连 / 要直连 / 直连      -> direct
#   走代理 / 要代理 / 代理        -> proxy
#   需要屏蔽 / 屏蔽 / block       -> block
#
# The head is auto-classified:
#   contains "/"                 -> ip_cidr (CIDR, e.g. 192.168.0.0/16)
#   all digits and dots           -> ip_cidr /32 (e.g. 8.8.8.8)
#   starts with "." or "*"         -> domain_suffix (e.g. .cn, *.cn)
#   anything else                  -> domain (e.g. google.com)
#
# Blank lines and lines starting with "#" are ignored.
#
_DIRECT_WORDS = ("需要直连", "要直连", "直连", "直接连", "直接访问")
_PROXY_WORDS = ("走代理", "要代理", "代理", "走代理", "需要代理")
_BLOCK_WORDS = ("需要屏蔽", "屏蔽", "block", "拦截", "要屏蔽")


def _classify_value(value):
    """Return (json_type, json_key, [values]) for one rule head."""
    v = value.strip()
    if not v:
        return None
    if "/" in v:
        return ("ip_cidr", "ip_cidr", [v])
    if v.replace(".", "").isdigit():
        return ("ip_cidr", "ip_cidr", [v + "/32"])
    if v.startswith(".") or v.startswith("*"):
        return ("domain_suffix", "domain_suffix", [v.lstrip("*")])
    return ("domain", "domain", [v])


def _parse_rules(text):
    """Parse the natural rule syntax into a list of rule dicts.

    Returns (rules, None) on success, or (None, error_message) on failure.
    """
    rules = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        outbound = None
        for word in _DIRECT_WORDS:
            if line.endswith(word):
                outbound = "direct"
                head = line[:-len(word)]
                break
        if outbound is None:
            for word in _PROXY_WORDS:
                if line.endswith(word):
                    outbound = "proxy"
                    head = line[:-len(word)]
                    break
        if outbound is None:
            for word in _BLOCK_WORDS:
                if line.endswith(word):
                    outbound = "block"
                    head = line[:-len(word)]
                    break
        if outbound is None:
            return None, "没有识别出站词（直连 / 代理 / 屏蔽）: %r" % raw
        head = head.strip()
        if not head:
            return None, "缺少域名或 IP: %r" % raw
        rtype, key, values = _classify_value(head)
        if rtype is None:
            return None, "无法识别的值: %r" % head
        rules.append({"type": rtype, key: values, "outbound": outbound})
    if not rules:
        return None, "没有解析到任何规则"
    return rules, None


def _int_or(text, default):
    """Parse a string into an int, falling back to `default` on blank/bad input."""
    try:
        return int(str(text).strip())
    except (TypeError, ValueError):
        return default


def _rules_to_text(rules):
    """Render rule dicts back into the natural syntax for the text box."""
    lines = []
    for r in rules:
        rtype = r.get("type", "domain")
        values = r.get(rtype, [])
        outbound = r.get("outbound", "proxy")
        if rtype == "domain":
            head = values[0] if values else ""
        elif rtype == "domain_suffix":
            head = values[0] if values else ""
        elif rtype == "ip_cidr":
            head = values[0] if values else ""
        else:
            head = ",".join(values)
        tail = {"direct": "需要直连", "proxy": "走代理",
                "block": "需要屏蔽"}.get(outbound, "走代理")
        lines.append("%s %s" % (head, tail))
    return "\n".join(lines)


class _QtLogHandler(logging.Handler):
    """Pump stdlib log records into the GUI log widget.

    Without this, logging.basicConfig writes to stderr and the user sees
    nothing in the 日志 tab — which reads as "the app is silent" even when
    it is working.
    """

    def __init__(self, window):
        super().__init__()
        self.window = window

    def emit(self, record):
        try:
            msg = self.format(record)
            self.window.log.appendPlainText(msg)
        except Exception:
            pass


class LetucApp:
    def __init__(self):
        self.qapp = QApplication(sys.argv)
        self.qapp.setApplicationName("letuc")
        self.config = Config.load_from_file(self._config_path())
        # Prefer the community rule sets when they are cached: they are far
        # more complete than the hand-written defaults. Custom rules saved
        # in the config file go first: the engine is first-match-wins, so a
        # user rule always beats the community lists underneath it.
        self.user_rules = self.config.get("rules", default=[]) or []
        self.community_rules = _rulesets.build_rules()
        self.engine = RuleEngine(self._merged_rules())
        self.client = None
        self.socks5 = None
        self.http = None
        self.tun = None
        self.window = MainWindow(self)
        self.tray = TrayIcon(self)
        # One loop for both Qt and asyncio. run_until_complete on a plain
        # loop would stop serving sockets the moment the call returned —
        # that is exactly the "listening but nobody accepts" freeze.
        self.loop = qasync.QEventLoop(self.qapp)
        asyncio.set_event_loop(self.loop)

        handler = _QtLogHandler(self.window)
        handler.setFormatter(logging.Formatter(
            "%(asctime)s %(levelname)s %(name)s: %(message)s"))
        root = logging.getLogger()
        root.addHandler(handler)
        root.setLevel(logging.INFO)

    @staticmethod
    def _config_path():
        # config.json lives next to the executable (or the repo root when
        # running from source), never inside the package directory
        if getattr(sys, "frozen", False):
            base = os.path.dirname(sys.executable)
        else:
            base = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
        return os.path.join(base, "config.json")

    def _merged_rules(self):
        """User rules in front of community rules: first match wins."""
        return self.user_rules + self.community_rules

    def rebuild_engine(self):
        """Rebuild the routing engine after any rule-list mutation."""
        self.engine = RuleEngine(self._merged_rules())

    def run(self):
        # --minimized: launched by the shell at boot, so stay in the tray
        # instead of popping a window in the user's face.
        if "--minimized" in sys.argv:
            self.window.hide()
        else:
            self.window.show()
        if self.config.get("anti_detection", "clock_check_on_startup"):
            self._check_clock()
        # 启动时自动设置系统代理 promises the proxy is actually UP after
        # boot, not just that the app launched. The Run entry only starts
        # letuc --minimized; without this the tunnel stays down and the
        # system proxy points at a dead port.
        if self.config.get("anti_detection", "set_system_proxy_on_start",
                           default=False):
            self.window._on_start()
        # qasync stops the asyncio side when the QApplication quits, so a
        # tray quit unwinds both halves in order.
        with self.loop:
            self.loop.run_forever()
        return 0

    def _check_clock(self):
        import time
        import urllib.request
        try:
            t = int(urllib.request.urlopen(
                "http://worldtimeapi.org/api/time/zone/Etc/UTC",
                timeout=5).read().split(b'"unixtime":')[1].split(b",")[0])
            if abs(t - int(time.time())) > mieru.MAX_TIME_SKEW:
                QMessageBox.warning(
                    self.window, "时钟偏差",
                    "本地时钟与 NTP 偏差超过 4 分钟，mieru 协议要求更小偏差。"
                    "请同步系统时间后重启。")
        except Exception:
            pass

    async def start_services(self):
        if self.client is not None:
            return
        host, port, user, pw = self._active_preset()
        mtu = self.config.get("tun", "mtu", default=1400)

        self.client = MieruClient(host, port, user, pw, mtu)
        await self.client.start()

        listen = self.config.get("proxy", "listen", default="127.0.0.1")
        mixed = self.config.get("proxy", "mixed", default=20808)
        socks = self.config.get("proxy", "socks", default=3080)
        pac = self.config.get("proxy", "pac", default=20811)
        xray_api = self.config.get("proxy", "xray_api", default=20812)
        mihomo_api = self.config.get("proxy", "mihomo_api", default=20813)

        self.mixed = MixedProxyServer(listen, mixed, self.engine, self.client)
        self.socks5 = Socks5Server(listen, socks, self.engine, self.client)
        # HTTP is served from the mixed port: MixedProxyServer peeks the
        # first byte and dispatches SOCKS5 to Socks5Server and everything
        # else to HttpProxyServer. So HttpProxyServer must NOT open its
        # own listener — starting it here would bind the mixed port twice.
        self.http = HttpProxyServer(listen, port=mixed, engine=self.engine,
                                    client=self.client)
        self.pac = PacServer(listen, pac, mixed=mixed, socks=socks)
        self.xray = ControlApiServer(listen, xray_api, self.engine, self.client, "xray")
        self.mihomo = ControlApiServer(listen, mihomo_api, self.engine, self.client, "mihomo")
        for srv in (self.mixed, self.socks5, self.pac, self.xray, self.mihomo):
            await srv.start()

        if self.config.get("tun", "enabled", default=False):
            self.tun = TunStack(
                client=self.client, server_ip=host,
                router=TunRouter(self.engine, server_ip=host),
                loop=self.loop)
            try:
                self.tun.start()
            except Exception as e:
                logger.warning("TUN unavailable, continuing without it: %s", e)
                self.window.log.appendPlainText(
                    "TUN 启动失败（%s），已跳过 TUN 继续运行" % e)
                self.tun = None
            self.window.set_status(
                f"running  mixed {listen}:{mixed}  socks {listen}:{socks}  pac {pac}  xray_api {xray_api}  mihomo_api {mihomo_api}  TUN")
        else:
            self.tun = None
            self.window.set_status(
                f"running  mixed {listen}:{mixed}  socks {listen}:{socks}  pac {pac}  xray_api {xray_api}  mihomo_api {mihomo_api}")

        # Let browsers and terminal apps find the local proxy without
        # anyone having to configure them. Best-effort: failures are logged
        # and the client keeps working. The active server must be in the
        # bypass list — sending the server's own traffic back through the
        # proxy would loop it straight into the tunnel. The subprocess
        # calls run on a worker thread: blocking the shared loop here
        # freezes both the GUI and every proxied connection.
        try:
            exceptions = self.config.get(
                "anti_detection", "system_proxy_exceptions",
                default="localhost;127.*;10.*;172.*;192.168.*")
            host = self._active_preset()[0]
            if host and host not in exceptions:
                exceptions = exceptions + ";" + host
            await asyncio.to_thread(
                sysproxy.set_internet_options_proxy, listen, mixed, exceptions)
            await asyncio.to_thread(
                sysproxy.set_winhttp_proxy, listen, mixed)
        except Exception as e:
            logger.warning("system proxy setup failed: %s", e)

    def _active_preset(self):
        """Resolve the currently selected server preset to (host, port, user, pw)."""
        presets = self.config.get("server", "presets", default=[])
        active = self.config.get("server", "active", default=None)
        if not active and presets:
            active = presets[0]["name"]
        for p in presets:
            if p.get("name") == active:
                return (p["host"], p["port"], p["username"], p["password"])
        # fall back to the legacy flat fields if a preset is missing
        return (self.config.get("server", "host"),
                self.config.get("server", "port"),
                self.config.get("auth", "username"),
                self.config.get("auth", "password"))

    async def stop_services(self):
        for srv in (self.mixed, self.socks5, self.http, self.pac, self.xray, self.mihomo):
            if srv is not None:
                await srv.stop()
        if getattr(self, "tun", None):
            self.tun.stop()
            self.tun = None
        if self.client:
            await self.client.stop()
            self.client = None
        self.mixed = self.socks5 = self.http = None
        self.pac = self.xray = self.mihomo = None
        self.window.set_status("stopped")

    async def _quit(self):
        """Stop everything and tear down the system proxy before exiting.

        This is the single exit path: the tray's quit entry, the window's
        quit button and the app shutdown all funnel through here. Clearing
        the system proxy matters — if we simply vanish, browsers keep
        pointing at a proxy that no longer exists and ordinary sites break.
        """
        if self.client is not None or any(
                getattr(self, n) is not None
                for n in ("mixed", "socks5", "http", "tun")):
            try:
                await self.stop_services()
            except Exception as e:
                logger.warning("error while stopping services: %s", e)
        try:
            await asyncio.to_thread(sysproxy.clear_internet_options_proxy)
            await asyncio.to_thread(sysproxy.clear_winhttp_proxy)
        except Exception as e:
            logger.warning("failed to clear system proxy on exit: %s", e)
        self.qapp.quit()


